// Smart Comment Synthesis Generator Engine
export function generateSmartComment(
  criteria: SmartCommentCriteria,
  seedVariantIndex = 0
): GeneratedCommentOutput {
  const {
    achievement,
    attitude,
    skill,
    progress,
    pronoun = "You",
    studentName = ""
  } = criteria;

  const subj = studentName ? studentName : pronoun;
  const isThirdPerson = subj !== "You";
  const hasVerb = isThirdPerson ? "has" : "have";
  const verbShow = isThirdPerson ? "shows" : "show";
  const verbDemonstrate = isThirdPerson ? "demonstrates" : "demonstrate";
  const verbSpeak = isThirdPerson ? "speaks" : "speak";
  const verbParticipate = isThirdPerson ? "participates" : "participate";
  const verbWork = isThirdPerson ? "works" : "work";
  const posPronoun = isThirdPerson ? (pronoun === "She" ? "her" : "his") : "your";

  // 1. Short Version (5-10 words)
  const shortOptions: Record<string, string[]> = {
    Excellent: [
      `Excellent progress. Keep up the great work!`,
      `Outstanding effort and results this year!`,
      `A wonderful year of learning. Well done!`
    ],
    "Very good": [
      `Very good work. Keep it up!`,
      `Great effort throughout the year. Well done!`,
      `Impressive progress this year. Keep shining!`
    ],
    Good: [
      `Good progress this year. Well done!`,
      `Solid effort and steady improvement!`,
      `Good work. Keep trying your best!`
    ],
    Satisfactory: [
      `Well done on your steady progress!`,
      `Keep working hard and stay positive!`,
      `Good effort made throughout the year.`
    ],
    "Making progress": [
      `Encouraging progress. Keep practicing daily!`,
      `Noticeable progress this year. Well done!`,
      `Keep learning and believing in yourself!`
    ],
    "Needs more practice": [
      `Keep practicing and never give up!`,
      `Stay focused and practice regularly!`,
      `You can make even greater progress!`
    ]
  };

  const shortList = shortOptions[achievement] || shortOptions["Good"];
  const shortVersion = shortList[seedVariantIndex % shortList.length];

  // 2. Standard Version (1-2 sentences)
  let standard1 = "";
  let standard2 = "";

  if (achievement === "Excellent") {
    const listA = [
      `${subj} ${hasVerb} made excellent progress in English this year and consistently demonstrated a positive attitude towards learning.`,
      `${subj} ${hasVerb} achieved outstanding results throughout the year and shown strong dedication to learning.`,
      `${subj} ${hasVerb} worked very hard and demonstrated exceptional learning skills in English.`
    ];
    standard1 = listA[seedVariantIndex % listA.length];
  } else if (achievement === "Very good" || achievement === "Good") {
    const listB = [
      `${subj} ${hasVerb} made good progress this year and shown a positive, responsible attitude towards learning.`,
      `${subj} ${hasVerb} worked well this year and achieved steady progress across English lessons.`,
      `${subj} ${hasVerb} participated actively in class and shown consistent effort throughout the year.`
    ];
    standard1 = listB[seedVariantIndex % listB.length];
  } else if (achievement === "Making progress" || achievement === "Satisfactory") {
    const listC = [
      `${subj} ${hasVerb} made encouraging progress this year and become visibly more confident in learning.`,
      `${subj} ${hasVerb} shown steady improvement and worked hard throughout the school year.`,
      `${subj} ${hasVerb} demonstrated clear progress and positive engagement in class activities.`
    ];
    standard1 = listC[seedVariantIndex % listC.length];
  } else {
    // Needs more practice
    const listD = [
      `${subj} ${hasVerb} made progress this year and would benefit from regular daily practice to build greater confidence.`,
      `${subj} is making steady progress, and continuing to practice regularly will help develop ${posPronoun} skills further.`,
      `${subj} has good potential in English and can achieve even better results with more regular practice.`
    ];
    standard1 = listD[seedVariantIndex % listD.length];
  }

  // Skill-specific second sentence
  if (skill === "Speaking") {
    standard2 = achievement === "Needs more practice"
      ? `Keep practicing speaking English regularly to speak with greater fluency and ease.`
      : `${subj} ${verbSpeak} English with confidence and ${verbParticipate} enthusiastically in speaking activities.`;
  } else if (skill === "Listening") {
    standard2 = achievement === "Needs more practice"
      ? `Continuing to listen to familiar English songs and stories will boost ${posPronoun} comprehension.`
      : `${subj} ${hasVerb} developed good listening comprehension and understands classroom English well.`;
  } else if (skill === "Reading") {
    standard2 = achievement === "Needs more practice"
      ? `Reading simple texts often will help expand ${posPronoun} vocabulary and reading confidence.`
      : `${subj} reads simple English texts with growing confidence and good comprehension.`;
  } else if (skill === "Writing") {
    standard2 = achievement === "Needs more practice"
      ? `Reviewing spelling and sentence patterns will help improve writing accuracy.`
      : `${subj} can write simple English sentences clearly and accurately.`;
  } else if (skill === "Vocabulary") {
    standard2 = achievement === "Needs more practice"
      ? `Reviewing new words regularly with flashcards will help use vocabulary more confidently.`
      : `${subj} ${hasVerb} learned and used a rich range of English vocabulary effectively.`;
  } else if (skill === "Pronunciation") {
    standard2 = achievement === "Needs more practice"
      ? `Practicing ending sounds and intonation regularly will make pronunciation even clearer.`
      : `${posPronoun.charAt(0).toUpperCase() + posPronoun.slice(1)} pronunciation has improved remarkably, speaking clearly and accurately.`;
  } else {
    // General
    standard2 = achievement === "Needs more practice"
      ? `Keep practicing regularly to build your confidence and communication skills.`
      : `Keep up the excellent work and continue to challenge yourself!`;
  }

  const standardVersion = `${standard1} ${standard2}`.trim();

  // 3. Warm & Encouraging Version (1-2 sentences with warm, motivating tone)
  let warmEncouragingVersion = "";
  if (achievement === "Excellent" || achievement === "Very good") {
    const warmList = [
      `A truly wonderful year of learning and growth! I am so proud of your hard work, enthusiastic spirit, and impressive achievements in English. Keep shining bright!`,
      `You bring so much joy and positive energy into our English classroom. Your dedication and outstanding progress have been a pleasure to watch. Keep reaching for the stars!`,
      `Congratulations on a fabulous school year! Your love for learning English and your caring attitude make you a fantastic learner. Continue to shine and inspire!`
    ];
    warmEncouragingVersion = warmList[seedVariantIndex % warmList.length];
  } else if (achievement === "Good" || achievement === "Satisfactory" || achievement === "Making progress") {
    const warmList = [
      `It has been a real pleasure seeing you grow in confidence and skill this year. Your steady effort and cheerful smile make every lesson better. Keep believing in yourself!`,
      `I am so pleased with the encouraging progress you have made this year. Always remember that every small step counts, and you have what it takes to do wonderful things!`,
      `Your sincere effort and positive attitude have brought wonderful improvements this year. Keep practicing, stay curious, and always be proud of your progress!`
    ];
    warmEncouragingVersion = warmList[seedVariantIndex % warmList.length];
  } else {
    // Needs more practice
    const warmList = [
      `You have great potential and a kind heart. Never be afraid of making mistakes, because every mistake is a chance to learn and grow. I know you can do it!`,
      `You have made meaningful steps forward this year. With a little more daily practice and self-belief, you will become even more confident in English. Keep trying your best!`,
      `Be proud of how far you have come! Keep exploring English with curiosity and patience. Thầy/cô always believes in you and your bright future!`
    ];
    warmEncouragingVersion = warmList[seedVariantIndex % warmList.length];
  }

  // 4. Variations for diversity control (4 alternative distinct sentences for this same evaluation)
  const variations = [
    `${subj} ${hasVerb} shown ${progress.toLowerCase()} throughout the year, approaching each lesson with a ${attitude.toLowerCase()} attitude.`,
    `A commendable year for ${subj}, marked by steady learning gains and active classroom participation.`,
    `${subj} ${verbWork} hard and consistently demonstrates dedication to developing ${posPronoun} English abilities.`,
    `With a positive learning mindset, ${subj} ${hasVerb} made encouraging strides in English communication this year.`
  ];

  return {
    shortVersion,
    standardVersion,
    warmEncouragingVersion,
    variations
  };
}
